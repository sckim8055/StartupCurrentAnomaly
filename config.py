"""
config.py — 이 실습 전체에서 쓰는 설정값을 한곳에 모아 둔 파일
=====================================================================

[왜 설정을 한 파일에 모으나?]
- 숫자가 여러 파일에 흩어져 있으면, 한 곳만 바꾸고 다른 곳은 그대로 두는 실수가 생긴다.
  예) 자료를 만들 때는 1초당 500개, 실시간 감지에서는 1000개로 읽으면 모델이 엉뚱한 판정을 한다.
- 그래서 "자료 만들기 → 학습 → 평가 → 실시간 적용" 네 단계가 모두 이 파일을 import 해서 같은 값을 쓴다.

[시나리오]
- 공장의 유압 프레스(압력기)를 움직이는 3상 유도전동기가 '시동'할 때 들어오는 전류를 감시한다.
- 전동기는 시동 순간 정격의 5~7배 전류(돌입 전류, inrush current)가 흐르고,
  회전이 붙으면서 전류가 빠르게 줄어들어 정격 전류 근처에서 안정된다.
- 이 "모양"이 평소와 다르면 설비에 문제가 생기고 있다는 신호다. (자세한 이상 유형은 simulate.py)
- 전류 단위는 '정격 전류 대비 배수(p.u., per unit)'로 쓴다. 1.0 = 정격 전류.
  실제 현장에서는 전류 센서(CT)로 읽은 암페어(A) 값을 정격 전류로 나누면 같은 단위가 된다.
"""
from pathlib import Path

# ----------------------------------------------------------------------------- 폴더
ROOT = Path(__file__).resolve().parent          # 이 파일이 있는 폴더 = 프로젝트 폴더
DATA_DIR = ROOT / "data"                        # simulate.py 가 만든 자료
MODEL_DIR = ROOT / "models"                     # train.py 가 만든 모델
REPORT_DIR = ROOT / "reports"                   # evaluate.py 가 만든 평가 결과·그림
LOG_DIR = ROOT / "logs"                         # run_realtime.py 가 남기는 판정 기록
MODEL_PATH = MODEL_DIR / "startup_ae.pt"        # 학습된 모델 파일 (현장에 가져가는 것은 이 파일 하나)

# ----------------------------------------------------------------------------- 센서·파형
FS = 500                # 샘플링 주파수: 1초에 전류 값을 500번 읽는다 (실제 현장은 1~10 kHz도 흔함)
WINDOW_SEC = 2.0        # 시동 1건 = 시동 시작부터 2초 동안의 파형
WIN = int(FS * WINDOW_SEC)   # = 1000개 샘플. 모델 입력 길이
TRIGGER = 0.5           # 전류가 정격의 0.5배를 넘는 순간을 '시동 시작'으로 본다
REARM = 0.2             # 판정이 끝난 뒤, 전류가 0.2배 아래로 내려가야(= 전동기 정지) 다음 시동을 기다린다
                        # 이 값이 없으면, 2초 판정 뒤에도 계속 돌고 있는 전동기의 전류(≈1.0)를 '새 시동'으로 착각한다
PRE_IDLE = 200          # 실시간 흉내 자료에서 시동과 시동 사이의 정지 구간 길이(샘플 수)

# 판정 결과를 사람이 이해하기 쉽게 '구간'으로 나눈다 (시작 샘플, 끝 샘플)
SEGMENTS = {
    "돌입(0~0.2s)": (0, 100),       # 돌입 전류가 치솟는 구간
    "감쇠(0.2~0.8s)": (100, 400),   # 전류가 줄어드는 구간
    "안정(0.8~2s)": (400, 1000),    # 정격 근처에서 안정된 구간
}

# ----------------------------------------------------------------------------- 자료 개수
# train      : 정상만. 모델이 "정상이 어떤 모양인지" 배우는 자료
# validation : 정상만. 학습을 언제 멈출지(조기 종료)와 경보선(임계값)을 정하는 자료 — 학습에는 쓰지 않는다
# test       : 정상 + 이상(정답 표시 있음). 마지막에 딱 한 번 성능을 재는 자료 — 학습·경보선 결정에 절대 쓰지 않는다
N_TRAIN = 1200
N_VAL = 400
N_TEST_NORMAL = 400
N_TEST_PER_ANOMALY = 40   # 이상 유형마다 40건

# 자료마다 다른 난수 씨앗(seed)을 써서, 세 자료가 서로 겹치지 않게 한다. 같은 씨앗이면 언제 실행해도 같은 자료가 나온다(재현성).
SEED_TRAIN, SEED_VAL, SEED_TEST, SEED_STREAM = 1, 2, 3, 4
SEED_TORCH = 0

# ----------------------------------------------------------------------------- 학습
LATENT = 16             # 오토인코더가 파형 1000개 값을 압축하는 숫자 개수 (병목 크기)
EPOCHS = 200            # 최대 학습 바퀴 수
PATIENCE = 20           # validation 손실이 20바퀴 동안 좋아지지 않으면 학습을 멈춘다 (조기 종료)
BATCH = 64
LR = 1e-3

# ----------------------------------------------------------------------------- 경보선
# validation(정상)에서 나온 오차 점수 분포의 상위 0.5% 위치를 경보선으로 쓴다.
#  → 정상 시동 200번에 1번 정도는 오경보가 날 수 있다는 뜻. 현장에서는 오경보 비용을 보고 조정한다.
THRESHOLD_QUANTILE = 0.995
THRESHOLD_MARGIN = 1.2  # 위 값에 20% 여유를 더한다 (validation 자료가 유한해서 생기는 흔들림 대비)
RULE_SIGMA = 5.0        # 간단한 기준(최대 전류·안정 전류)의 정상 범위 = 평균 ± 5 표준편차
